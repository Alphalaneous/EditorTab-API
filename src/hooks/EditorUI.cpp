void ETEditorUI::toggleMode(cocos2d::CCObject* sender) {
    int mode = sender->getTag();

    if (m_selectedMode != mode) {
        auto fields = m_fields.self();

        EditorSFXManager::sharedState()->playAction(169);

        std::string modeID;
        switch (sender->getTag()) {
            case 1: {
                modeID = alpha::editor_tabs::Delete;
                break;
            }
            case 2: {
                modeID = alpha::editor_tabs::Build;
                break;
            }
            case 3: {
                modeID = alpha::editor_tabs::Edit;
                break;
            }
            case 4: {
                modeID = alpha::editor_tabs::View;
                break;
            }
        }

        resetUI();
        switchMode(modeID);
    }

    updateSpecialTabVisibility();
}

void ETEditorUI::showUI(bool show) {
    EditorUI::showUI(show);
    
    if (!GameManager::get()->getGameVariable(GameVar::PlaytestNoUI)) {
        show = true;
    }

    if (show) {
        updateSpecialTabVisibility();
    }

    auto mode = getCurrentMode();
    if (!mode) return;

    if (show) {
        mode->showMode();
    }
    else {
        mode->hideMode();
    }
}

void ETEditorUI::updateSpecialTabVisibility() {
    auto mode = getCurrentMode();
    if (!mode) return;

    auto tab = mode->getCurrentTab();
    if (!tab) return;

    if (mode->getID() == alpha::editor_tabs::Delete) {
        m_deleteMenu->setVisible(tab->getID() == "delete" && !m_uiHidden);
    }
    if (mode->getID() == alpha::editor_tabs::Edit) {
        if (m_editButtonBar) {
            m_editButtonBar->setVisible(tab->getID() == "edit" && !m_uiHidden);
        }
        else if (m_dpadMoveNode) {
            m_dpadMoveNode->setVisible(tab->getID() == "edit" && !m_uiHidden);
        }
    }
    if (mode->getID() == alpha::editor_tabs::View) {
        m_viewMenu->setVisible(tab->getID() == "view" && !m_uiHidden);
    }
}

